def apply_country(country: str) -> None:
    path = ROOT / "content" / "pois" / f"{country}.json"
    pois = json.loads(path.read_text(encoding="utf-8"))
    by_number = {poi["n"]: poi for poi in pois}

    for number, links in LINKS.get(country, {}).items():
        by_number[number]["links"] = links
    for number, coordinates in COORDS.get(country, {}).items():
        by_number[number]["lat"], by_number[number]["lon"] = coordinates
    for number, name in NAMES.get(country, {}).items():
        by_number[number]["name"] = name
    for number, dog_policy in DOGS.get(country, {}).items():
        by_number[number]["dog"] = dog_policy
    for number, description in DESCRIPTIONS.get(country, {}).items():
        by_number[number]["desc"] = description
    for number, details in VISITS.get(country, {}).items():
        by_number[number]["visit"] = details
    for number, photos in PHOTOS.get(country, {}).items():
        by_number[number]["photos"] = photos
        primary = photos[0]
        by_number[number]["img"] = primary["img"]
        by_number[number]["source"] = primary["source"]
        by_number[number]["credit"] = primary["credit"]

    path.write_text(json.dumps(pois, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    for country_name in sorted(LINKS):
        apply_country(country_name)
